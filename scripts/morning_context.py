#!/usr/bin/env python3
"""
Prepare mandatory morning context before Lisa's editorial cycle.

This script is intentionally deterministic: it only reads local state and writes
one dated context file that the heartbeat instructions can require Lisa to load.
"""
import datetime
import os
from pathlib import Path


WORKSPACE = Path(os.path.expanduser("~/.openclaw/workspace"))
CACHE = WORKSPACE / "cache"
TODAY = datetime.date.today()
YESTERDAY = TODAY - datetime.timedelta(days=1)
DISCOVERY_WINDOW_START = f"{YESTERDAY:%Y-%m-%d} 18:00 Europe/Prague"
RECENT_REJECTED_LIMIT = 20


def read_if_exists(path: Path) -> str:
    if not path.exists():
        return ""
    return path.read_text(encoding="utf-8", errors="replace")


def read_recent_jsonl_lines(path: Path, limit: int) -> str:
    if not path.exists():
        return ""
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    lines = [line for line in lines if line.strip()]
    if not lines:
        return ""
    return "\n".join(lines[-limit:])


def main() -> int:
    CACHE.mkdir(parents=True, exist_ok=True)

    today_learning = CACHE / f"session_learnings_{TODAY:%Y-%m-%d}.md"
    yesterday_learning = CACHE / f"session_learnings_{YESTERDAY:%Y-%m-%d}.md"
    rejected_topics = CACHE / "rejected_topics.jsonl"
    output = CACHE / f"morning_context_{TODAY:%Y-%m-%d}.md"
    latest = CACHE / "morning_context_latest.md"

    yesterday_text = read_if_exists(yesterday_learning)
    today_text = read_if_exists(today_learning)
    rejected_text = read_recent_jsonl_lines(rejected_topics, RECENT_REJECTED_LIMIT)

    content = f"""# Morning Context — {TODAY:%Y-%m-%d}

Generated by: `scripts/morning_context.py`

## Mandatory Use

If this file is current, Lisa MUST load and apply it before DATA GATE, signal scoring,
Roman Test, portfolio selection and report writing.
If it is missing or stale, continue with live data and log a WARNING instead of stopping the cycle.

## Yesterday Learning

Source: `{yesterday_learning}`

{yesterday_text if yesterday_text else "(no yesterday learning file found)"}

## Today Learning / Current Corrections

Source: `{today_learning}`

{today_text if today_text else "(no today learning file found)"}

## Recent Rejected Topics

Source: `{rejected_topics}`

{rejected_text if rejected_text else "(no rejected topics file found)"}

## Hard Editorial Rules For This Run

- Discovery scan window for this run: from {DISCOVERY_WINDOW_START} to now.
- Do not start editorial discovery only from the last manual test or last search checkpoint.
- Evening test runs do not consume the morning discovery window; rescan the whole window.
- Do not repeat a rejected topic unless there is a new concrete news peg.
- Do not promote SEO gaps into CREATE unless Roman Test passes.
- Run duplicate/cannibalization checks before CREATE.
- Run intent overlap check before every CREATE, not just exact duplicate match.
- Check rejected topics history before every CREATE and treat SAME_INTENT / TOO_CLOSE_TO_EXISTING / UPDATE_ONLY style hits as blockers for Vrstva 1.
- Each magazine should leave the cycle with at least 20 topics whenever DATA GATE passes and live + GSC data are available.
- Vrstva 1 target: 5-8 breaking/fresh CREATE topics from the overnight live scan.
- Vrstva 2 target: 12-15 GSC/evergreen topics from the verified data base, typically CREATE / UPDATE / REWRITE depending on existing coverage freshness.
- Evergreen from GSC is the required backbone of the morning plan, not an optional fallback.
- Vrstva 1 must contain only strong CREATE slots that can stand as standalone stories now.
- Vrstva 2 is a curated evergreen/data layer, never a dump for weak duplicates or unverified claims.
- Every Vrstva 1 topic needs 3 title variants labelled Discover / Search / Balanced plus one recommended pick with a short why.
- If Roman or Tom rejects a topic today, save it into rejected_topics.jsonl and append the lesson to today's session learning file immediately.
- If ready, prefer Google SERP Search API and Google SERP Trends Search API as primary search/trends layer.
- If ready, use Competitor Research for borderline topics and seo-content for uniqueness / quality angle validation.
- Morning output must include 3 per-magazine PDFs as the primary deliverable.
- Use Python + ReportLab as the stable PDF method for the morning plan.
- Canonical PDF names: roman-ranni-plan-lsa-YYYYMMDD.pdf, roman-ranni-plan-android-YYYYMMDD.pdf, roman-ranni-plan-samsung-YYYYMMDD.pdf.
- If ready, use humanizer on final headlines and short annotations before PDF.
- If Google Trends primary provider fails, use pytrends; never invent Trends data.
- API and credential checks must run in the main session, never in subagents.
"""

    output.write_text(content, encoding="utf-8")
    latest.write_text(content, encoding="utf-8")
    print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
